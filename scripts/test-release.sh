# The parts of scripts/release.sh that need no Mac: which VERSION may be released, the engine's
# version constant as the release compares it, the drivers.json reader, the source download's
# SHA-256 check and the release's asset list. Then the Makefile's release targets, and
# scripts/cut-release.sh: its version arithmetic and CHANGELOG rewrite, and whole runs in a scratch
# repository with a bare origin, where make, brew, Xcode's tools, security and gh are stubs that
# log what they were asked. The signing, notarization and DMG steps run only on the Mac
# (docs/plans/distribution.md, "Sign, notarize, package", Verification).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
# shellcheck source=release.sh
. "$here/release.sh"
set +e

tmp=$(mktemp -d "${TMPDIR:-/tmp}/test-release.XXXXXX")
trap 'rm -rf "$tmp"' EXIT
failures=0
fail() { echo "FAIL: $*" >&2; failures=$((failures + 1)); }

for v in 0.1.0 0.1.1 1.2.3; do
  [ -z "$(release_version_refusal "$v")" ] || fail "$v was refused: $(release_version_refusal "$v")"
done
for v in "" 0.1.0-dev 0.2.0-dev.1 0.1.0+3 "0.1.0 x" 0.1.0/x; do
  [ -n "$(release_version_refusal "$v")" ] || fail "\"$v\" was not refused"
done

# The constant as scripts/gen-version.sh writes it.
cat > "$tmp/Version.swift" <<'SWIFT'
// SPDX-License-Identifier: GPL-3.0-or-later

// Generated by scripts/gen-version.sh from the root VERSION file. Do not edit.

/// The version reported in `DaemonInfo` and by `--version`.
let leylinedVersion = "0.1.2"
SWIFT
[ "$(engine_version "$tmp/Version.swift")" = 0.1.2 ] \
  || fail "engine_version read \"$(engine_version "$tmp/Version.swift")\""

# drivers.json as bundle-app.sh's bundle_drivers writes it, one driver per line.
mkdir -p "$tmp/src" "$tmp/out"
printf 'librtlsdr source\n' > "$tmp/src/rtl.tar.gz"
printf 'hackrf source\n' > "$tmp/src/hackrf.tar.xz"
sha_rtl=$(shasum -a 256 "$tmp/src/rtl.tar.gz" | awk '{print $1}')
sha_hackrf=$(shasum -a 256 "$tmp/src/hackrf.tar.xz" | awk '{print $1}')
cat > "$tmp/out/drivers.json" <<JSON
{
  "drivers": [
    {"library": "librtlsdr.0.dylib", "formula": "librtlsdr", "version": "2.0.2", "source_url": "https://example.com/rtl/v2.0.2.tar.gz", "sha256": "$sha_rtl"},
    {"library": "libhackrf.0.dylib", "formula": "hackrf", "version": "2024.02.1", "source_url": "https://example.com/hackrf/hackrf-2024.02.1.tar.xz", "sha256": "$sha_hackrf"}
  ]
}
JSON
want="librtlsdr-2.0.2-source.tar.gz|https://example.com/rtl/v2.0.2.tar.gz|$sha_rtl
hackrf-2024.02.1-source.tar.xz|https://example.com/hackrf/hackrf-2024.02.1.tar.xz|$sha_hackrf"
got=$(driver_sources "$tmp/out/drivers.json")
[ "$got" = "$want" ] || fail "driver_sources printed:
$got
want:
$want"

printf '{"drivers": [\n    {"library": "x.dylib", "formula": "x", "source_url": "https://example.com/x.zip", "sha256": "00"}\n]}\n' \
  > "$tmp/missing.json"
driver_sources "$tmp/missing.json" >/dev/null 2>&1 && fail "driver_sources accepted a driver without a version"

# curl on PATH is a stub that serves the files above by the URL's last path element.
mkdir -p "$tmp/bin"
cat > "$tmp/bin/curl" <<SH
#!/usr/bin/env bash
out=; url=
while [ \$# -gt 0 ]; do case "\$1" in -o) out=\$2; shift 2 ;; -*) shift ;; *) url=\$1; shift ;; esac; done
case "\$url" in
  */v2.0.2.tar.gz) cp "$tmp/src/rtl.tar.gz" "\$out" ;;
  */hackrf-2024.02.1.tar.xz) cp "$tmp/src/hackrf.tar.xz" "\$out" ;;
  *) exit 22 ;;
esac
SH
chmod +x "$tmp/bin/curl"
PATH="$tmp/bin:$PATH" fetch_driver_sources "$tmp/out/drivers.json" "$tmp/out" >/dev/null \
  || fail "fetch_driver_sources failed against matching tarballs"
[ -f "$tmp/out/librtlsdr-2.0.2-source.tar.gz" ] && [ -f "$tmp/out/hackrf-2024.02.1-source.tar.xz" ] \
  || fail "fetch_driver_sources did not write both tarballs: $(ls "$tmp/out")"

printf 'tampered\n' > "$tmp/src/hackrf.tar.xz"
PATH="$tmp/bin:$PATH" fetch_driver_sources "$tmp/out/drivers.json" "$tmp/out" >/dev/null 2>&1 \
  && fail "fetch_driver_sources accepted a tarball whose SHA-256 differs"

want="$tmp/out/Leyline-0.1.2.dmg
$tmp/out/leysdr-0.1.2-source.tar.gz
$tmp/out/librtlsdr-2.0.2-source.tar.gz
$tmp/out/hackrf-2024.02.1-source.tar.xz
$tmp/out/drivers.json
$tmp/out/appcast.xml"
got=$(release_assets "$tmp/out" 0.1.2)
[ "$got" = "$want" ] || fail "release_assets printed:
$got
want:
$want"

# The Makefile's release targets, as make -n prints their recipes: release cuts a release and
# passes the version's knobs through, release-build, release-publish and release-rehearse call
# scripts/release.sh, and there is no alpha target.
mk() { make --no-print-directory -n -C "$here/.." "$@" 2>&1; }
case "$(mk release NEXT=0.4.2 BUMP=minor YES=1 DRY_RUN=1)" in
  *'NEXT="0.4.2" BUMP="minor" YES="1" DRY_RUN="1" ./scripts/cut-release.sh'*) ;;
  *) fail "make release runs: $(mk release NEXT=0.4.2 BUMP=minor YES=1 DRY_RUN=1)" ;;
esac
case "$(mk release-build)" in *'./scripts/release.sh') ;; *) fail "make release-build runs: $(mk release-build)" ;; esac
case "$(mk release-publish)" in *'./scripts/release.sh publish') ;; *) fail "make release-publish runs: $(mk release-publish)" ;; esac
case "$(mk release-rehearse OUT=/x)" in *'./scripts/release.sh rehearse "/x"') ;; *) fail "make release-rehearse runs: $(mk release-rehearse OUT=/x)" ;; esac
mk alpha >/dev/null && fail "the Makefile still has an alpha target"

# --- scripts/release-appcast.sh and scripts/cut-release.sh

# shellcheck source=release-appcast.sh
. "$here/release-appcast.sh"
# shellcheck source=cut-release.sh
. "$here/cut-release.sh"
set +e

# next_version: X-dev releases as X; a released X.Y.Z is followed by the next patch, or by the
# next minor or major with a bump.
for case in 0.1.0-dev::0.1.0 1.0.0-dev::1.0.0 0.1.0::0.1.1 0.1.9::0.1.10 0.1.0:patch:0.1.1 \
  0.1.3:minor:0.2.0 0.9.3:major:1.0.0 1.2.3:minor:1.3.0 0.10.0::0.10.1; do
  IFS=: read -r from bump want <<<"$case"
  got=$(next_version "$from" "$bump")
  [ "$got" = "$want" ] || fail "next_version $from ${bump:-(no bump)} printed \"$got\", want $want"
done
for case in 0.1.0-rc.1: 0.1.0-beta.1: 0.1: 0.1.0.1: 01.2.3: -dev: : 0.1.0-dev:minor 0.1.0:huge \
  0.1-dev: 0.1.0-rc.1-dev:; do
  IFS=: read -r from bump <<<"$case"
  next_version "$from" "$bump" >/dev/null 2>&1 && fail "next_version accepted \"$from\" ${bump:+with $bump}"
done

for pair in 0.1.1:0.1.0 0.2.0:0.1.9 1.0.0:0.99.99 0.1.10:0.1.9 0.10.0:0.9.0; do
  version_gt "${pair%%:*}" "${pair#*:}" || fail "version_gt says ${pair%%:*} is not greater than ${pair#*:}"
  version_gt "${pair#*:}" "${pair%%:*}" && fail "version_gt says ${pair#*:} is greater than ${pair%%:*}"
done
version_gt 0.1.0 0.1.0 && fail "version_gt says 0.1.0 is greater than itself"

# last_release: the greatest vX.Y.Z tag by number, not by name; other tags are not releases.
git init -q "$tmp/tags"
(cd "$tmp/tags" && git -c user.name=T -c user.email=t@example.com commit -q --allow-empty -m x \
  && for t in v0.1.9 v0.1.10 v0.1.2 v0.2.0-rc.1 v1 shots-2026-10-05; do git tag "$t"; done)
got=$(cd "$tmp/tags" && last_release)
[ "$got" = 0.1.10 ] || fail "last_release printed \"$got\", want 0.1.10"
got=$(cd "$tmp/tags" && git tag -d v0.1.9 v0.1.10 v0.1.2 >/dev/null && last_release)
[ -z "$got" ] || fail "last_release printed \"$got\" with no vX.Y.Z tag"

# The first release drops the sentence saying nothing has been released, and leaves an empty
# Unreleased above the dated section.
cat > "$tmp/CHANGELOG.md" <<'MD'
# Changelog

Nothing has been released yet. This file starts with everything that exists on `main`.

## Unreleased

- A thing.

- Another thing.
MD
[ "$(unreleased_notes "$tmp/CHANGELOG.md")" = "- A thing.

- Another thing." ] || fail "unreleased_notes printed: $(unreleased_notes "$tmp/CHANGELOG.md")"
changelog_cut "$tmp/CHANGELOG.md" 0.1.0 2026-10-05 || fail "changelog_cut failed"
want='# Changelog

## Unreleased

## 0.1.0 (2026-10-05)

- A thing.

- Another thing.'
[ "$(cat "$tmp/CHANGELOG.md")" = "$want" ] || fail "changelog_cut wrote:
$(cat "$tmp/CHANGELOG.md")
want:
$want"
[ -z "$(unreleased_notes "$tmp/CHANGELOG.md")" ] || fail "the new Unreleased section is not empty"
[ "$(notes_for 0.1.0 "$tmp/CHANGELOG.md")" = "- A thing.

- Another thing." ] || fail "notes_for does not read the dated heading: $(notes_for 0.1.0 "$tmp/CHANGELOG.md")"
changelog_has_section 0.1.0 "$tmp/CHANGELOG.md" || fail "changelog_has_section missed the dated heading"
changelog_has_section 0.1 "$tmp/CHANGELOG.md" && fail "changelog_has_section matched a prefix"

# The second release keeps the first's section below its own.
printf '%s\n' '# Changelog' '' '## Unreleased' '' '- New.' '' '## 0.1.0 (2026-10-05)' '' '- Old.' \
  > "$tmp/CHANGELOG.md"
changelog_cut "$tmp/CHANGELOG.md" 0.1.1 2026-10-12 || fail "changelog_cut failed on the second release"
want='# Changelog

## Unreleased

## 0.1.1 (2026-10-12)

- New.

## 0.1.0 (2026-10-05)

- Old.'
[ "$(cat "$tmp/CHANGELOG.md")" = "$want" ] || fail "changelog_cut on the second release wrote:
$(cat "$tmp/CHANGELOG.md")"
[ "$(notes_for 0.1.1 "$tmp/CHANGELOG.md")" = "- New." ] || fail "notes_for 0.1.1 is wrong"
printf '# Changelog\n\n- No heading.\n' > "$tmp/nohead.md"
changelog_cut "$tmp/nohead.md" 0.1.0 2026-10-05 && fail "changelog_cut accepted a changelog without ## Unreleased"
[ "$(cat "$tmp/nohead.md")" = "$(printf '# Changelog\n\n- No heading.')" ] || fail "changelog_cut changed a file it refused"

# Stubs for whole runs. Each scenario's $STUB directory holds switches (files) and the logs.
stubs=$tmp/stubs
