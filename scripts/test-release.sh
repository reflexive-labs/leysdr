chmod +x "$stubs"/*

# scenario <name>: a scratch repository at $repo with a bare origin, VERSION 0.1.0-dev, the
# scripts cut-release.sh runs and a first-release CHANGELOG, pushed; $STUB holds its switches and
# logs.
scenario() {
  local s=$tmp/scenario-$1
  mkdir -p "$s/stub"
  STUB=$s/stub
  repo=$s/work
  printf '%s\n' librtlsdr hackrf libusb > "$STUB/brew-installed"
  : > "$STUB/make.log"; : > "$STUB/gh.log"; : > "$STUB/credentials.log"
  git init -q --bare -b main "$s/origin.git"
  git init -q -b main "$repo"
  mkdir -p "$repo/scripts" "$repo/engine/Sources/LeylineDaemon" "$repo/go/internal/cli"
  cp "$here/cut-release.sh" "$here/release.sh" "$here/release-appcast.sh" "$here/gen-version.sh" "$repo/scripts/"
  echo 0.1.0-dev > "$repo/VERSION"
  printf 'package cli\n\nconst defaultVersion = "0.1.0-dev"\n' > "$repo/go/internal/cli/root.go"
  printf '/dist/\n' > "$repo/.gitignore"
  cat > "$repo/CHANGELOG.md" <<'MD'
# Changelog

Nothing has been released yet. This file starts with everything that exists on `main`.

## Unreleased

- The first thing.
MD
  (cd "$repo" && ./scripts/gen-version.sh >/dev/null \
    && git config user.name Tester && git config user.email tester@example.com \
    && git config commit.gpgsign false && git config tag.gpgsign false \
    && git add -A && git commit -q -m "start" && git remote add origin "$s/origin.git" \
    && git push -q origin main)
}

# report <prefix> <lines>: one failure per non-empty line.
report() {
  local line
  while IFS= read -r line; do
    [ -z "$line" ] || fail "$1: $line"
  done <<<"$2"
}

# cutrel [VAR=value…]: scripts/cut-release.sh in $repo with the stubs first on PATH, YES=1 unless
# given; its output in $out, its status returned.
cutrel() {
  out=$(cd "$repo" && env PATH="$stubs:$PATH" STUB="$STUB" TMPDIR="$tmp" MAKE=make YES=1 \
    CODESIGN_IDENTITY="Developer ID Application: Test Labs (TEAM123)" NOTARY_PROFILE=test-notary \
    "$@" ./scripts/cut-release.sh 2>&1 </dev/null)
}

# note <text>: a line under CHANGELOG.md's `## Unreleased` in $repo, committed and pushed.
note() {
  (cd "$repo" && awk -v n="- $1" '{ print } /^## Unreleased$/ { print ""; print n }' CHANGELOG.md > CHANGELOG.new \
    && cat CHANGELOG.new > CHANGELOG.md && rm CHANGELOG.new && git commit -q -am "notes" && git push -q origin main)
}

# snapshot: what a refused or rehearsed run must leave as it was.
snapshot() {
  (cd "$repo" && git rev-parse HEAD && git status --porcelain && git tag && cat VERSION CHANGELOG.md \
    && git ls-remote origin)
}

# refused <want> [VAR=value…]: the run stops, changes nothing, and its last line ends with <want>.
refused() {
  local want=$1 before
  shift
  before=$(snapshot)
  if cutrel "$@"; then
    fail "cut-release ran where it should have stopped with \"…$want\":
$out"
    return
  fi
  case "$(printf '%s\n' "$out" | tail -1)" in
    cut-release:*"$want") ;;
    *) fail "cut-release's last line does not end with \"$want\":
$out" ;;
  esac
  [ "$(snapshot)" = "$before" ] || fail "cut-release changed the repository while refusing (\"$want\")"
}

# rehearsed <version> [VAR=value…]: a rehearsal that names <version> as the next release.
rehearsed() {
  local want=$1
  shift
  cutrel DRY_RUN=1 "$@" || { fail "the rehearsal with $* failed:
$out"; return; }
  case "$out" in *"Next release: $want "*) ;; *) fail "the rehearsal with $* did not name $want:
$out" ;; esac
}

# released <version> <date>: what a finished release of <version> leaves in $repo, one problem
# per line.
released() {
  local v=$1
  (
    cd "$repo" || exit 1
    [ "$(cat VERSION)" = "$v" ] || echo "VERSION is $(cat VERSION)"
    [ "$(git log -1 --format=%s)" = "release: $v" ] || echo "HEAD is \"$(git log -1 --format=%s)\""
    git log -1 --format=%B | grep -q '^Signed-off-by: Tester <tester@example.com>$' || echo "the release commit is not signed off"
    [ "$(git cat-file -t "v$v")" = tag ] || echo "v$v is not an annotated tag"
    [ "$(git rev-parse "v$v^{commit}")" = "$(git rev-parse HEAD)" ] || echo "the tag is not at HEAD"
    [ "$(git show --name-only --format= HEAD | sort | xargs)" \
      = "CHANGELOG.md VERSION engine/Sources/LeylineDaemon/Version.swift go/internal/cli/root.go" ] \
      || echo "the release commit holds: $(git show --name-only --format= HEAD | xargs)"
    grep -q "leylinedVersion = \"$v\"" engine/Sources/LeylineDaemon/Version.swift || echo "Version.swift was not regenerated"
    grep -q "defaultVersion = \"$v\"" go/internal/cli/root.go || echo "root.go was not regenerated"
    grep -q '^Nothing has been released' CHANGELOG.md && echo "the first-release sentence is still there"
    grep -qx "## $v ($(date +%Y-%m-%d))" CHANGELOG.md || echo "CHANGELOG.md has no dated section"
    [ "$(git ls-remote origin refs/heads/main | cut -f1)" = "$(git rev-parse HEAD)" ] || echo "main was not pushed"
    git ls-remote --exit-code origin "refs/tags/v$v" >/dev/null || echo "the tag was not pushed"
  )
}

# A whole run: VERSION 0.1.0-dev releases as 0.1.0; the commit and tag come before the build, the
# build sees the tag, then the push and the publish.
scenario full
cutrel || fail "the full run failed:
$out"
report "full run" "$(released 0.1.0)"
[ "$(cat "$STUB/make.log")" = "make version
make release-build 0.1.0 describe=v0.1.0
make release-publish 0.1.0" ] || fail "the full run called make as:
$(cat "$STUB/make.log")"
case "$out" in *"Two steps are left"*"Acceptance, on a second"*"pins v0.1.0"*) ;; *) fail "the full run did not name what is left:
$out" ;; esac

# release.sh publish uses the pushed tag rather than making one, and makes a full release that
# does not take Latest from the shots-* releases.
(cd "$repo" && env PATH="$stubs:$PATH" STUB="$STUB" ./scripts/release.sh publish >/dev/null 2>&1) \
  || fail "release.sh publish failed after the full run"
create=$(grep 'release create v0.1.0 ' "$STUB/gh.log")
case "$create" in *--verify-tag*) ;; *) fail "release.sh publish did not pass --verify-tag: $create" ;; esac
case "$create" in *--target*) fail "release.sh publish passed --target beside an existing tag: $create" ;; esac
case "$create" in *--prerelease*) fail "release.sh publish made a prerelease: $create" ;; esac
case "$create" in *--latest=false*) ;; *) fail "release.sh publish did not pass --latest=false: $create" ;; esac

# Run again on the finished release, it changes nothing and builds and publishes nothing.
: > "$STUB/make.log"
cutrel || fail "a second run on a finished release failed:
$out"
[ ! -s "$STUB/make.log" ] || fail "a second run on a finished release called make: $(cat "$STUB/make.log")"
[ "$(cd "$repo" && git log --format=%s | grep -c '^release:')" = 1 ] || fail "a second run cut another release"

# After the release VERSION is 0.1.0, and the next is 0.1.1 unless BUMP or NEXT says otherwise.
note "The second thing."
rehearsed 0.1.1
rehearsed 0.1.1 BUMP=patch
rehearsed 0.2.0 BUMP=minor
rehearsed 1.0.0 BUMP=major
rehearsed 0.4.2 NEXT=0.4.2
refused "make release NEXT=<version>" NEXT=0.1.0
refused "make release NEXT=<version>" NEXT=0.0.9
case "$out" in *"0.0.9 is not greater than 0.1.0"*) ;; *) fail "NEXT=0.0.9 was refused for another reason:
$out" ;; esac
refused "make release NEXT=<version>" NEXT=0.2.0-rc.1
refused "make release NEXT=<version>" NEXT=0.2
refused "make release BUMP=minor" BUMP=huge
refused "make release NEXT=0.3.0" NEXT=0.3.0 BUMP=minor
: > "$STUB/make.log"
cutrel || fail "the second release failed:
$out"
report "second release" "$(released 0.1.1)"
[ "$(cat "$STUB/make.log")" = "make version
make release-build 0.1.1 describe=v0.1.1
make release-publish 0.1.1" ] || fail "the second release called make as:
$(cat "$STUB/make.log")"
[ "$(cd "$repo" && grep -c '^## 0\.1\.[01] (' CHANGELOG.md)" = 2 ] || fail "the second release lost the first's section:
$(cat "$repo/CHANGELOG.md")"

# A tag greater than VERSION's next patch, made outside make release, is the last release.
note "The third thing."
(cd "$repo" && git tag -a v0.3.0 -m x)
refused "make release NEXT=<version>"
case "$out" in *"0.1.2 is not greater than 0.3.0"*) ;; *) fail "the run below v0.3.0 was refused for another reason:
$out" ;; esac
rehearsed 0.4.0 NEXT=0.4.0
(cd "$repo" && git tag -d v0.3.0 >/dev/null)

# A build that fails leaves the commit and tag; the next run builds again from them, without a
# second bump.
scenario resume
touch "$STUB/fail-release"
cutrel && fail "the run whose build fails succeeded"
(cd "$repo" && [ "$(git log -1 --format=%s)" = "release: 0.1.0" ] && git rev-parse -q --verify refs/tags/v0.1.0 >/dev/null) \
  || fail "the failed run did not leave the release commit and tag"
(cd "$repo" && git ls-remote --exit-code origin refs/tags/v0.1.0 >/dev/null) && fail "the failed run pushed the tag"
case "$(printf '%s\n' "$out" | tail -1)" in *"make release-build failed"*": make release") ;; *) fail "the failed run's last line is: $(printf '%s\n' "$out" | tail -1)" ;; esac
rm "$STUB/fail-release"
cutrel || fail "the resumed run failed:
$out"
case "$out" in *"carrying on"*"unfinished; building it again"*) ;; *) fail "the resumed run did not say it carried on and rebuilt:
$out" ;; esac
problems=$(
  cd "$repo" || exit 1
  [ "$(cat VERSION)" = 0.1.0 ] || echo "VERSION is $(cat VERSION)"
  [ "$(git log --format=%s | grep -c '^release:')" = 1 ] || echo "there are $(git log --format=%s | grep -c '^release:') release commits"
  [ -f dist/0.1.0/commit ] || echo "dist/0.1.0 was not rebuilt"
  git ls-remote --exit-code origin refs/tags/v0.1.0 >/dev/null || echo "the tag was not pushed"
)
report "resumed run" "$problems"
[ "$(grep -c '^make release-build 0.1.0' "$STUB/make.log")" = 2 ] && grep -q '^make release-publish' "$STUB/make.log" \
  && [ "$(grep -c '^make version' "$STUB/make.log")" = 1 ] \
  || fail "the two runs called make as:
$(cat "$STUB/make.log")"

# A run stopped between the commit and the tag: the next one tags HEAD and goes on.
scenario untagged
(cd "$repo" && echo 0.1.0 > VERSION && ./scripts/gen-version.sh >/dev/null \
  && git commit -q -a -m "release: 0.1.0")
cutrel || fail "the run after an untagged release commit failed:
$out"
[ "$(cd "$repo" && git rev-parse 'v0.1.0^{commit}')" = "$(cd "$repo" && git rev-parse HEAD)" ] \
  || fail "the run after an untagged release commit did not tag HEAD"

# A rehearsal changes nothing, asks for no credentials, and builds through release-rehearse.
scenario dry
before=$(snapshot)
cutrel DRY_RUN=1 || fail "the rehearsal failed:
$out"
[ "$(snapshot)" = "$before" ] || fail "the rehearsal changed the repository"
[ "$(cat "$STUB/make.log")" = "make release-rehearse 0.1.0-dev" ] || fail "the rehearsal called make as: $(cat "$STUB/make.log")"
[ ! -s "$STUB/credentials.log" ] && [ ! -s "$STUB/gh.log" ] \
  || fail "the rehearsal checked credentials: $(cat "$STUB/credentials.log" "$STUB/gh.log")"
case "$out" in *"Next release: 0.1.0 "*"Rehearsal of 0.1.0 done"*"Skipped:"*) ;; *) fail "the rehearsal did not say what it built and skipped:
$out" ;; esac

# A missing driver formula is installed, not refused.
grep -v hackrf "$STUB/brew-installed" > "$STUB/b" && mv "$STUB/b" "$STUB/brew-installed"
cutrel DRY_RUN=1 || fail "the rehearsal without hackrf failed:
$out"
grep -qx 'brew install hackrf' "$STUB/brew.log" || fail "the missing formula was not installed: $(cat "$STUB/brew.log")"

# NEXT names the version; before the first release, X-dev is the version and BUMP has nothing to
# pick.
rehearsed 0.2.0 NEXT=0.2.0
[ "$(snapshot)" = "$before" ] || fail "the rehearsal with NEXT changed the repository"

# Refusals: each stops before changing anything, its last line ending in the command that fixes it.
scenario refusals
refused "make release NEXT=<version>" NEXT=0.2.0-dev
refused "make release NEXT=<version>" BUMP=minor
refused "Run it there with: make release" STUB_UNAME=Linux
(cd "$repo" && git switch -q -c feature)
refused "git switch main"
(cd "$repo" && git switch -q main && echo x >> VERSION)
refused "git stash -u"
(cd "$repo" && git checkout -q -- VERSION && git commit -q --allow-empty -m ahead && git push -q origin main \
  && git reset -q --hard HEAD~1)
refused "git pull --ff-only origin main"
(cd "$repo" && git pull -q --ff-only origin main)
touch "$STUB/no-identity"
refused "security import <file>.p12 -k ~/Library/Keychains/login.keychain-db"
rm "$STUB/no-identity"; touch "$STUB/no-notary"
refused "xcrun notarytool store-credentials test-notary --apple-id <Apple ID> --team-id TEAM123"
rm "$STUB/no-notary"; touch "$STUB/no-gh"
refused "gh auth login"
rm "$STUB/no-gh"
(cd "$repo" && git tag -a v0.1.0 -m x HEAD~0 2>/dev/null)
refused "make release NEXT=<version>"
(cd "$repo" && git tag -d v0.1.0 >/dev/null)
refused "Run again when ready, with YES=1 to skip this question: make release" YES=
(cd "$repo" && printf '# Changelog\n\n## Unreleased\n\n## 0.0.1 (2026-01-01)\n\n- Old.\n' > CHANGELOG.md \
  && git commit -q -am "empty notes" && git push -q origin main)
refused "\$EDITOR CHANGELOG.md"

if [ $failures -gt 0 ]; then
  echo "test-release.sh: $failures failed" >&2
  exit 1
fi
echo "test-release.sh: ok"
