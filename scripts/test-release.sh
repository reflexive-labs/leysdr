# make: version runs the real generator; release-build lays out dist/<VERSION>/ as
# scripts/release.sh does, or a partial one and a failure when $STUB/fail-release exists, and logs
# what git describe says at that moment; release-publish and release-rehearse only log. Any other
# target, release itself included, is a failure.
cat > "$stubs/make" <<'SH'
#!/usr/bin/env bash
target=; out=
for a in "$@"; do case "$a" in --*) ;; OUT=*) out=${a#OUT=} ;; *) target=$a ;; esac; done
v=$(tr -d '[:space:]' < VERSION)
case "$target" in
  version) echo "make version" >> "$STUB/make.log"; ./scripts/gen-version.sh >/dev/null ;;
  release-build)
    echo "make release-build $v describe=$(git describe --tags --exact-match 2>/dev/null)" >> "$STUB/make.log"
